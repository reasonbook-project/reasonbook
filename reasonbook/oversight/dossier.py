"""Oversight cycle dossier — ReportLab PDF.

Generates a committee-ready summary of all oversight decisions resolved
in a cycle (IG audit window, audit-committee meeting, appropriations
cycle, etc.). Calibration: works correctly, no iterative visual polish —
operational decision PDFs are where polish effort lands.
"""

from __future__ import annotations

import uuid
from io import BytesIO
from typing import Any

from reportlab.lib import colors
from reportlab.lib.pagesizes import LETTER
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.platypus import (
    BaseDocTemplate,
    Frame,
    PageTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
)

from reasonbook.db import session_scope
from reasonbook.models import Decision, OversightCycle, Tenant
from reasonbook.oversight import OVERSIGHT_WORKFLOW_ID

DEEP_NAVY = colors.HexColor("#042C53")
INK = colors.HexColor("#1A1A1A")
INK_SECONDARY = colors.HexColor("#5A5A5A")
INK_TERTIARY = colors.HexColor("#9A9A9A")
HAIRLINE = colors.HexColor("#E2E2DD")


def _styles() -> dict[str, ParagraphStyle]:
    base = getSampleStyleSheet()
    body = base["BodyText"]
    return {
        "masthead": ParagraphStyle(
            "masthead",
            parent=body,
            fontName="Times-Roman",
            fontSize=22,
            leading=26,
            textColor=DEEP_NAVY,
            spaceAfter=4,
        ),
        "subhead": ParagraphStyle(
            "subhead",
            parent=body,
            fontName="Helvetica",
            fontSize=11,
            textColor=INK_SECONDARY,
            spaceAfter=18,
        ),
        "h2": ParagraphStyle(
            "h2",
            parent=body,
            fontName="Helvetica-Bold",
            fontSize=10,
            leading=14,
            textColor=INK_SECONDARY,
            spaceBefore=14,
            spaceAfter=6,
        ),
        "decision_title": ParagraphStyle(
            "decision_title",
            parent=body,
            fontName="Times-Bold",
            fontSize=12,
            leading=16,
            textColor=DEEP_NAVY,
            spaceAfter=4,
        ),
        "value": ParagraphStyle(
            "value",
            parent=body,
            fontName="Helvetica",
            fontSize=10,
            leading=14,
            textColor=INK,
            spaceAfter=4,
        ),
        "label": ParagraphStyle(
            "label",
            parent=body,
            fontName="Helvetica-Bold",
            fontSize=8,
            textColor=INK_TERTIARY,
            spaceAfter=2,
        ),
    }


def _draw_footer(canvas, doc) -> None:  # type: ignore[no-untyped-def]
    canvas.saveState()
    width, _ = LETTER
    canvas.setFont("Helvetica", 8)
    canvas.setFillColor(INK_TERTIARY)
    canvas.drawString(
        0.75 * inch,
        0.5 * inch,
        "Oversight Cycle Dossier · Generated by Reasonbook",
    )
    canvas.drawRightString(width - 0.75 * inch, 0.5 * inch, f"Page {doc.page}")
    canvas.setStrokeColor(HAIRLINE)
    canvas.setLineWidth(0.5)
    canvas.line(0.75 * inch, 0.7 * inch, width - 0.75 * inch, 0.7 * inch)
    canvas.restoreState()


def render_cycle_dossier(cycle_id: uuid.UUID) -> bytes:
    """Render an oversight cycle's resolved decisions as a committee-ready PDF."""
    s = _styles()
    buffer = BytesIO()

    with session_scope() as session:
        cycle = session.get(OversightCycle, cycle_id)
        if cycle is None:
            raise ValueError("cycle not found")
        tenant = session.get(Tenant, cycle.tenant_id)
        decisions = (
            session.query(Decision)
            .filter(
                Decision.workflow_id == OVERSIGHT_WORKFLOW_ID,
                Decision.oversight_cycle_id == cycle_id,
            )
            .order_by(Decision.decided_at.asc().nullslast())
            .all()
        )
        decided = [d for d in decisions if d.decided_at is not None]
        open_count = len(decisions) - len(decided)

        story: list[Any] = [
            Paragraph("Reasonbook — Oversight Cycle Dossier", s["masthead"]),
            Paragraph(
                f"{cycle.name} · {cycle.cycle_start.isoformat()} → "
                f"{cycle.cycle_end.isoformat()} · {tenant.name if tenant else cycle.tenant_id}",
                s["subhead"],
            ),
            Paragraph("Executive summary", s["h2"]),
            Paragraph(
                f"{len(decided)} oversight decisions resolved this cycle; "
                f"{open_count} remained open at cycle close. "
                f"Cycle type: {cycle.cycle_type}.",
                s["value"],
            ),
            Spacer(1, 0.15 * inch),
            Paragraph("Resolved decisions", s["h2"]),
        ]

        for d in decided:
            story.append(Paragraph(d.title, s["decision_title"]))
            story.append(
                Paragraph(
                    f"{d.decision_number} · {d.decision_type} · "
                    f"decided {d.decided_at.strftime('%b %d, %Y') if d.decided_at else '—'}",
                    s["label"],
                )
            )
            if d.rationale:
                story.append(Paragraph(d.rationale, s["value"]))
            if d.target_outcome:
                story.append(Paragraph(f"<b>Target outcome:</b> {d.target_outcome}", s["value"]))
            story.append(Spacer(1, 0.12 * inch))

        if open_count > 0:
            story.append(Paragraph("Decisions still open at cycle close", s["h2"]))
            for d in decisions:
                if d.decided_at is not None:
                    continue
                story.append(
                    Paragraph(
                        f"{d.title} <font color='#9A9A9A'>({d.decision_number})</font>",
                        s["value"],
                    )
                )

        story.append(Spacer(1, 0.2 * inch))
        story.append(
            Paragraph(
                "Generated by Reasonbook.",
                ParagraphStyle(
                    "footnote",
                    parent=s["value"],
                    fontSize=8,
                    textColor=INK_TERTIARY,
                    fontName="Helvetica",
                ),
            )
        )

    doc = BaseDocTemplate(
        buffer,
        pagesize=LETTER,
        leftMargin=0.75 * inch,
        rightMargin=0.75 * inch,
        topMargin=0.75 * inch,
        bottomMargin=0.85 * inch,
    )
    frame = Frame(
        doc.leftMargin,
        doc.bottomMargin,
        doc.width,
        doc.height,
        id="body",
    )
    doc.addPageTemplates(PageTemplate(id="default", frames=[frame], onPage=_draw_footer))
    doc.build(story)

    # Suppress unused import warning — TableStyle/Table available for future polish.
    _ = (Table, TableStyle)
    return buffer.getvalue()
