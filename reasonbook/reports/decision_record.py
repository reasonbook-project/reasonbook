"""Examiner-grade Decision Record PDF.

Renders the full five-stage anatomy of a decision into a printable artifact.
The cover carries the brand mark, "Reasonbook" masthead, decision
ID, and tenant; subsequent pages walk Signal → Owner → Decision → Action →
Outcome; the footer credits "Generated by Reasonbook"
on every page per design-system §5.5.
"""

from __future__ import annotations

import json
import uuid
from io import BytesIO
from typing import Any

from reportlab.lib import colors
from reportlab.lib.enums import TA_LEFT
from reportlab.lib.pagesizes import LETTER
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.platypus import (
    BaseDocTemplate,
    Frame,
    PageTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
)

from reasonbook.db import session_scope
from reasonbook.models import Decision, DecisionEvent, Tenant, User
from reasonbook.semantic.engine import get_engine

# Generic stage labels — fallback when the decision isn't a federal
# program (oversight workflow, ad-hoc decisions, etc.).
_GENERIC_STAGE_LABELS: dict[str, str] = {
    "signal": "SIGNAL",
    "owner": "OWNER",
    "decision": "DECISION",
    "action": "ACTION",
    "outcome": "OUTCOME",
}


def _resolve_stage_labels(workflow_id: str) -> dict[str, str]:
    """Return ``maps_to → label`` for the PDF's five stage headers.

    For a federal program (workflow_id is a program id), uses the bound
    archetype's stage labels — competitive_award → "Application receipt",
    "Eligibility screen", "Merit review", "Authority decision", "Award or
    decline". Program-level ``stage_overrides`` win when present (e.g.
    nih-r01 specializes "Authority decision" → "Advisory council & IC
    director").

    Falls back to the generic Signal/Owner/Decision/Action/Outcome labels
    for any workflow_id the semantic engine doesn't know as a program.
    """
    engine = get_engine()
    if workflow_id not in engine.program_ids():
        return dict(_GENERIC_STAGE_LABELS)

    program = engine.get_program(workflow_id)
    archetype = engine.archetype_for_program(workflow_id)
    overrides = getattr(program, "stage_overrides", None) or {}

    labels: dict[str, str] = {}
    for stage in archetype.stages:
        override = overrides.get(stage.id) or {}
        label = override.get("label") if isinstance(override, dict) else None
        labels[stage.maps_to] = (label or stage.label).upper()
    # Fill any unmapped maps_to with the generic label as a safety net.
    for key, fallback in _GENERIC_STAGE_LABELS.items():
        labels.setdefault(key, fallback)
    return labels

# Design-system tokens (mirrored — keep in sync with web/src/index.css §3).
BRAND_BLUE = colors.HexColor("#3162AA")
DEEP_NAVY = colors.HexColor("#042C53")
