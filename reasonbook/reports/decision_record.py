INK_SECONDARY = colors.HexColor("#5A5A5A")
INK_TERTIARY = colors.HexColor("#9A9A9A")
HAIRLINE = colors.HexColor("#E2E2DD")


def _styles() -> dict[str, ParagraphStyle]:
    base = getSampleStyleSheet()
    body = base["BodyText"]
    return {
        "masthead": ParagraphStyle(
            "masthead",
            parent=body,
            fontName="Times-Roman",
            fontSize=22,
            leading=26,
            textColor=DEEP_NAVY,
            spaceAfter=4,
        ),
        "subhead": ParagraphStyle(
            "subhead",
            parent=body,
            fontName="Helvetica",
            fontSize=11,
            textColor=INK_SECONDARY,
            spaceAfter=18,
        ),
        "h2": ParagraphStyle(
            "h2",
            parent=body,
            fontName="Helvetica-Bold",
            fontSize=10,
            leading=14,
            textColor=INK_SECONDARY,
            spaceBefore=14,
            spaceAfter=6,
        ),
        "stage": ParagraphStyle(
            "stage",
            parent=body,
            fontName="Helvetica-Bold",
            fontSize=9,
            leading=14,
            textColor=INK_SECONDARY,
            spaceBefore=18,
            spaceAfter=6,
        ),
        "label": ParagraphStyle(
            "label",
            parent=body,
            fontName="Helvetica-Bold",
            fontSize=8,
            textColor=INK_TERTIARY,
            spaceAfter=2,
        ),
        "value": ParagraphStyle(
            "value",
            parent=body,
            fontName="Helvetica",
            fontSize=10,
            leading=14,
            textColor=INK,
            spaceAfter=6,
        ),
        "rationale": ParagraphStyle(
            "rationale",
            parent=body,
            fontName="Helvetica",
            fontSize=10,
            leading=15,
            textColor=INK,
            alignment=TA_LEFT,
            spaceAfter=10,
        ),
        "mono": ParagraphStyle(
            "mono",
            parent=body,
            fontName="Courier",
            fontSize=9,
            leading=12,
            textColor=INK_SECONDARY,
        ),
    }


def _draw_footer(canvas: Any, doc: Any) -> None:
    canvas.saveState()
    width, _ = LETTER
    canvas.setFont("Helvetica", 8)
    canvas.setFillColor(INK_TERTIARY)
    canvas.drawString(
        0.75 * inch,
        0.5 * inch,
        "Generated by Reasonbook",
    )
    canvas.drawRightString(width - 0.75 * inch, 0.5 * inch, f"Page {doc.page}")
    canvas.setStrokeColor(HAIRLINE)
    canvas.setLineWidth(0.5)
    canvas.line(0.75 * inch, 0.7 * inch, width - 0.75 * inch, 0.7 * inch)
    canvas.restoreState()


def _draw_chrome() -> Any:
    """Build the per-page draw callback."""

    def on_page(canvas: Any, doc: Any) -> None:
        _draw_footer(canvas, doc)

    return on_page


def _kv_table(rows: list[tuple[str, str]]) -> Table:
    """Two-column label/value table — used inside each stage section."""
    data = [
        [
            Paragraph(label, _styles()["label"]),
            Paragraph(value, _styles()["value"]),
        ]
        for label, value in rows
        if value
    ]
    if not data:
        data = [[Paragraph("—", _styles()["label"]), Paragraph("", _styles()["value"])]]
    table = Table(data, colWidths=[1.4 * inch, 5.0 * inch])
    table.setStyle(
        TableStyle(
            [
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("LEFTPADDING", (0, 0), (-1, -1), 0),
                ("RIGHTPADDING", (0, 0), (-1, -1), 0),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ]
        )
    )
    return table


def _format_dt(value: Any) -> str:
    if value is None:
        return ""
    return str(value.strftime("%b %d, %Y · %I:%M %p"))


def _safe_json(value: Any) -> str:
    if value is None:
        return ""
    try:
        return json.dumps(value, indent=2, default=str)
    except (TypeError, ValueError):
        return str(value)


def generate_decision_record_pdf(decision_id: uuid.UUID) -> bytes:
    """Render a Decision Record PDF for the given decision id.

    Loads the decision, its events, owner, and tenant in one session pass
    and returns the raw PDF bytes ready for a Flask response. Returns an
    empty bytes object if the decision doesn't exist (caller should 404
    instead of attempting download).
    """
    with session_scope() as session:
        decision = session.get(Decision, decision_id)
        if decision is None:
            return b""

        owner = session.get(User, decision.owner_id) if decision.owner_id else None
        creator = session.get(User, decision.created_by) if decision.created_by else None
        tenant = session.get(Tenant, decision.tenant_id)

        events = (
            session.query(DecisionEvent)
            .filter(DecisionEvent.decision_id == decision_id)
            .order_by(DecisionEvent.created_at.asc())
            .all()
        )

        styles = _styles()
        buf = BytesIO()
        doc = BaseDocTemplate(
            buf,
            pagesize=LETTER,
            leftMargin=0.75 * inch,
            rightMargin=0.75 * inch,
            topMargin=0.75 * inch,
            bottomMargin=0.85 * inch,
            title=f"Decision Record — {decision.decision_number}",
            author="Reasonbook",
        )
        frame = Frame(
            doc.leftMargin,
            doc.bottomMargin,
            doc.width,
            doc.height,
            id="body",
        )
        on_page = _draw_chrome()
        doc.addPageTemplates([PageTemplate(id="default", frames=[frame], onPage=on_page)])

        story: list[Any] = []

        # Cover masthead
        story.append(Paragraph("Reasonbook", styles["masthead"]))
        story.append(
            Paragraph(
                f"Decision record · {decision.decision_number}",
                styles["subhead"],
            )
        )
        story.append(
            _kv_table(
                [
                    ("Title", decision.title),
                    ("Workflow", decision.workflow_id),
                    (
                        "Tenant",
                        f"{tenant.name} ({decision.tenant_id})" if tenant else decision.tenant_id,
                    ),
                    ("Type", decision.decision_type),
                    ("Priority", decision.priority),
                    ("Status", decision.status),
                ]
            )
        )

        stage_labels = _resolve_stage_labels(decision.workflow_id)

        story.append(Paragraph(f"STAGE 1 · {stage_labels['signal']}", styles["stage"]))
        story.append(
            _kv_table(
                [
                    ("Captured", _format_dt(decision.signal_captured_at)),
                    ("Source", decision.signal_source or ""),
                    ("Summary", decision.signal_summary or ""),
                ]
            )
        )
        if decision.trigger_data:
            story.append(Paragraph("Trigger payload", styles["label"]))
            story.append(
                Paragraph(
                    f"<pre>{_safe_json(decision.trigger_data)}</pre>",
                    styles["mono"],
                )
            )

        story.append(Paragraph(f"STAGE 2 · {stage_labels['owner']}", styles["stage"]))
        story.append(
            _kv_table(
                [
                    ("Owner", owner.name if owner else "Unowned"),
                    ("Authority level", str(decision.owner_authority_level or "")),
                    ("Acknowledged", _format_dt(decision.acknowledged_at)),
                    (
                        "Created by",
                        creator.name if creator else "(system)",
                    ),
                ]
            )
        )
        if decision.escalation_path:
            story.append(Paragraph("Escalation path", styles["label"]))
            chain = " → ".join(
                f"{step.get('name', '?')} (L{step.get('level', '?')})"
                for step in decision.escalation_path
            )
            story.append(Paragraph(chain, styles["value"]))

        story.append(Paragraph(f"STAGE 3 · {stage_labels['decision']}", styles["stage"]))
        story.append(
            _kv_table(
                [
                    ("Decided", _format_dt(decision.decided_at)),
                    ("Selected option", decision.selected_option or ""),
                ]
            )
        )
        if decision.rationale:
            story.append(Paragraph("Rationale", styles["label"]))
            story.append(Paragraph(decision.rationale, styles["rationale"]))
        if decision.alternatives:
            story.append(Paragraph("Alternatives considered", styles["label"]))
            for alt in decision.alternatives:
                story.append(
                    Paragraph(
                        f"• {alt.get('id', '?')} — {alt.get('rejected_reason', '')}",
                        styles["value"],
                    )
                )
        if decision.evidence_refs:
            story.append(Paragraph("Evidence", styles["label"]))
            for ref in decision.evidence_refs:
                story.append(
                    Paragraph(
                        f"• {_safe_json(ref)}",
                        styles["mono"],
                    )
                )

        story.append(Paragraph(f"STAGE 4 · {stage_labels['action']}", styles["stage"]))
        story.append(
            _kv_table(
                [
                    ("Started", _format_dt(decision.action_started_at)),
                    ("Completed", _format_dt(decision.action_completed_at)),
                ]
            )
        )
        if decision.action_artifacts:
            story.append(Paragraph("Artifacts", styles["label"]))
            for art in decision.action_artifacts:
                story.append(Paragraph(f"• {_safe_json(art)}", styles["mono"]))

        story.append(Paragraph(f"STAGE 5 · {stage_labels['outcome']}", styles["stage"]))
        story.append(
            _kv_table(
                [
                    ("Recorded", _format_dt(decision.outcome_recorded_at)),
                    ("Impact", decision.outcome_impact or ""),
                ]
            )
        )
        if decision.outcome_text:
            story.append(Paragraph("Narrative", styles["label"]))
            story.append(Paragraph(decision.outcome_text, styles["rationale"]))
        if decision.outcome_metrics:
            story.append(Paragraph("Metrics", styles["label"]))
            for k, v in decision.outcome_metrics.items():
                story.append(Paragraph(f"<b>{k}</b>: {v}", styles["value"]))

        # Activity log appendix
        story.append(Spacer(1, 24))
        story.append(Paragraph("ACTIVITY LOG", styles["stage"]))
        log_rows = [
            [
                Paragraph(_format_dt(e.created_at), styles["mono"]),
                Paragraph(e.action, styles["value"]),
                Paragraph(
                    f"{e.old_status or '—'} → {e.new_status or '—'}",
                    styles["mono"],
                ),
                Paragraph(e.comment or "", styles["value"]),
            ]
            for e in events
        ]
        if log_rows:
            log_table = Table(
                log_rows,
                colWidths=[1.5 * inch, 1.4 * inch, 1.6 * inch, 2.0 * inch],
            )
            log_table.setStyle(
                TableStyle(
                    [
                        ("VALIGN", (0, 0), (-1, -1), "TOP"),
                        ("LINEBELOW", (0, 0), (-1, -1), 0.5, HAIRLINE),
                        ("TOPPADDING", (0, 0), (-1, -1), 4),
                        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                        ("LEFTPADDING", (0, 0), (-1, -1), 0),
                    ]
                )
            )
            story.append(log_table)

        doc.build(story)
        return buf.getvalue()
